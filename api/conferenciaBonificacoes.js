async function consultarVendasDasBonificacoes(notas, executarConsulta) {
  const ids = notas.filter((nota) => nota.TIPMOV === 'V' && Number(nota.CODTIPOPER) === 10)
    .map((nota) => Number(nota.NUNOTA)).filter((id) => Number.isSafeInteger(id) && id > 0);
  const vendas = new Map();
  for (let inicio = 0; inicio < ids.length; inicio += 500) {
    const lote = ids.slice(inicio, inicio + 500);
    const vinculos = await executarConsulta(`WITH BONIFICACOES AS (
      SELECT NUNOTA, CODEMP, CODPARC, DTFATUR FROM TGFCAB WHERE NUNOTA IN (${lote.join(', ')})
    ), ORIGENS AS (
      SELECT DISTINCT B.NUNOTA BONIFICACAO, V.NUNOTAORIG
      FROM BONIFICACOES B JOIN TGFVAR V ON V.NUNOTA=B.NUNOTA
      WHERE V.NUNOTAORIG<>B.NUNOTA
    ), VINCULOS AS (
      SELECT O.BONIFICACAO, O.NUNOTAORIG VENDA FROM ORIGENS O
      UNION
      SELECT O.BONIFICACAO, V.NUNOTA VENDA FROM ORIGENS O JOIN TGFVAR V ON V.NUNOTAORIG=O.NUNOTAORIG
      UNION
      SELECT B.NUNOTA, V.NUNOTA FROM BONIFICACOES B JOIN TGFVAR V ON V.NUNOTAORIG=B.NUNOTA
    ), CANDIDATOS AS (
      SELECT B.NUNOTA BONIFICACAO, C.NUNOTA VENDA, 1 PRIORIDADE
      FROM BONIFICACOES B JOIN VINCULOS V ON V.BONIFICACAO=B.NUNOTA
      JOIN TGFCAB C ON C.NUNOTA=V.VENDA AND C.CODEMP=B.CODEMP AND C.CODPARC=B.CODPARC
      WHERE C.TIPMOV='V' AND C.CODTIPOPER=35 AND C.STATUSNOTA IN ('A','P','L')
      UNION ALL
      SELECT B.NUNOTA, C.NUNOTA, 2
      FROM BONIFICACOES B JOIN TGFCAB C ON C.CODEMP=B.CODEMP AND C.CODPARC=B.CODPARC
        AND C.DTFATUR>=TRUNC(B.DTFATUR) AND C.DTFATUR<TRUNC(B.DTFATUR)+1
      WHERE C.TIPMOV='V' AND C.CODTIPOPER=35 AND C.STATUSNOTA IN ('A','P','L')
    ), CLASSIFICADOS AS (
      SELECT C.*, MIN(PRIORIDADE) OVER (PARTITION BY BONIFICACAO) MELHOR_PRIORIDADE
      FROM CANDIDATOS C
    )
    SELECT BONIFICACAO, MIN(VENDA) VENDA FROM CLASSIFICADOS
    WHERE PRIORIDADE=MELHOR_PRIORIDADE GROUP BY BONIFICACAO HAVING COUNT(DISTINCT VENDA)=1`);
    for (const vinculo of vinculos) vendas.set(Number(vinculo.BONIFICACAO), Number(vinculo.VENDA));
  }
  return vendas;
}

module.exports = { consultarVendasDasBonificacoes };
